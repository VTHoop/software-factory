import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { AGENTS, pluginFiles, skill } from "./lib.mjs";

const assertAbsent = (pattern, label) => {
  const files = pluginFiles();
  assert.ok(files.length > 0, "the plugin has no files yet");
  for (const [path, text] of files) {
    assert.doesNotMatch(text, pattern, `${label} in ${path}`);
  }
};

describe("no dependency on the machine", () => {
  it("does not read from ~/.claude or anyone's home directory", () => {
    assertAbsent(/~\/\.claude|\/Users\/|\$HOME/, "user-level path");
  });

  it("replaces repo-resolution with the current repo", () => {
    assertAbsent(/repo-resolution/, "repo-resolution");
    assert.match(skill("pr-review"), /current repo/i);
  });
});

describe("no project details", () => {
  it("names no project tooling or service", () => {
    assertAbsent(/\bpnpm\b|supabase|\bvercel\b|\bresend\b/i, "project tool");
  });

  it("names no project folders", () => {
    assertAbsent(/apps\/web|packages\/core|`server\/`|`api\/`|docs\/adr/, "project folder");
  });

  it("uses only the placeholder for issue keys", () => {
    // CWE ids are the security reviewer's references, not issue keys.
    for (const [path, text] of pluginFiles()) {
      for (const [key] of text.matchAll(/\b[A-Z]{2,}-\d+\b/g)) {
        assert.ok(/^(PROJ|CWE)-/.test(key), `${key} in ${path}`);
      }
    }
  });

  it("names no lowercase project branch", () => {
    assertAbsent(/\b[a-z]{2,}\/(?!proj-)[a-z]{2,}-\d+-/, "project branch");
  });

  it("does not assume the project has a Working agreements heading", () => {
    assertAbsent(/Working agreements/, "project heading");
  });
});

describe("no skills outside the plugin", () => {
  it("does not send the reader to an outside skill", () => {
    assertAbsent(/\/self-review|\/refine-ticket|\/retro\b|\/next-up/, "outside skill");
  });

  it("says the ticket needs refining where unclear AC stops a run", () => {
    assert.match(skill("start-ticket"), /needs refining/i);
  });

  it("calls its own skills by their namespaced names", () => {
    for (const [path, text] of pluginFiles()) {
      // The marker and heading keep their wording because the script reads them.
      const rest = text
        .replaceAll("Generated by `/pr-review`", "")
        .replaceAll("Response to /pr-review", "");
      assert.doesNotMatch(
        rest,
        /(^|[\s`("*])\/(pr-review|start-ticket|address-review)\b/m,
        path,
      );
    }
  });
});

describe("verification comes from the project", () => {
  for (const name of ["start-ticket", "address-review"]) {
    it(`${name} reads commands and rules from AGENTS.md`, () => {
      assert.match(skill(name), /`AGENTS\.md`/);
      assert.match(skill(name), /`## Verification`/);
      assert.match(skill(name), /project rules/i);
    });

    it(`${name} says so instead of guessing when the section is missing`, () => {
      assert.match(skill(name), /no `## Verification` section/i);
      assert.match(skill(name), /say so instead of guessing/i);
    });
  }
});

describe("pr-review spawns its own reviewers", () => {
  it("spawns all six by namespaced name", () => {
    for (const a of AGENTS) {
      assert.match(skill("pr-review"), new RegExp(`\`software-factory:${a}\``));
    }
  });

  it("never names a reviewer bare", () => {
    assert.doesNotMatch(skill("pr-review"), /`sdlc-review-/);
  });
});

describe("no prompt asks an agent to recount its reasoning", () => {
  it("has no such wording in any skill or agent", () => {
    assertAbsent(
      /(recount|recap|restate|repeat|summari[sz]e|explain|describe|walk through|share|show)\s+(\w+\s+){0,3}(reasoning|thinking|thought process|chain of thought)/i,
      "reasoning request",
    );
  });
});
