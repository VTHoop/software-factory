import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { block, skill } from "./lib.mjs";

const text = () => skill("pr-review");
const rereview = () => block(text(), "rereview") ?? "";

describe("pr-review records the commit it reviewed", () => {
  it("ends every review with the head commit it reviewed", () => {
    assert.match(text(), /\*Generated by `\/pr-review` · Lenses: [^\n]*· Reviewed at `<head sha>`\*/);
  });

  it("takes that commit from `git rev-parse origin/<head>`", () => {
    assert.match(text(), /`<head sha>` is `git rev-parse origin\/<head>`/);
  });
});

describe("pr-review --rereview", () => {
  it("is a flag read only from the skill's arguments", () => {
    assert.match(text(), /^argument-hint: .*--rereview/m);
    assert.match(text(), /`--rereview` is read only from this skill's arguments/);
  });

  it("has its own section", () => {
    assert.ok(rereview(), "no rereview block");
  });

  it("is one agent: it spawns no reviewers", () => {
    assert.match(rereview(), /spawn no reviewers/i);
    assert.match(rereview(), /you do the whole re-review yourself/i);
  });

  it("reads the latest trusted review and the trusted response after it", () => {
    assert.match(rereview(), /latest trusted review/i);
    assert.match(rereview(), /trusted `## Response to \/pr-review` comment posted after it/i);
  });

  it("falls back to the full review when it can't check only the changes", () => {
    assert.match(rereview(), /run the full review instead/i);
    assert.match(rereview(), /no `Reviewed at` commit/i);
    assert.match(rereview(), /`git merge-base --is-ancestor <reviewed sha> origin\/<head>`/);
    assert.match(rereview(), /more than half the lines the whole PR changes/i);
  });

  it("checks every row of the response against the code", () => {
    assert.match(rereview(), /\*\*Fixed\*\*.*`git show <sha>`/s);
    assert.match(rereview(), /\*\*Dismissed\*\*.*open the cited/is);
    assert.match(rereview(), /new test, written to dismiss/i);
    assert.match(rereview(), /\*\*Deferred\*\*/);
  });

  it("keeps a finding whose answer doesn't hold, at its severity", () => {
    assert.match(rereview(), /stands at its original severity/i);
    assert.match(rereview(), /a finding with no row stands/i);
  });

  it("reviews only the commits since the reviewed one, reading each touched file in full", () => {
    assert.match(rereview(), /`git diff <reviewed sha>\.\.origin\/<head>`/);
    assert.match(rereview(), /every file it touches in full with the Read tool/i);
  });

  it("writes the same comment format, so the Overall line and marker still parse", () => {
    assert.match(rereview(), /Output format/);
    assert.match(rereview(), /Lenses: re-review/);
  });

  it("validates what it raises before ranking it", () => {
    assert.match(rereview(), /Phase 4/);
  });

  it("in an unattended run, spawns no agents unless it falls back to the full review", () => {
    assert.match(block(text(), "unattended"), /with `--rereview`, spawn no review agents unless/i);
  });
});
