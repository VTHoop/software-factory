import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { REVIEWERS as NAMES } from "../../orchestrator/checks.mjs";

// A scratch directory that is removed when the test run ends.
const scratch = [];
process.on("exit", () => scratch.forEach((d) => rmSync(d, { recursive: true, force: true })));
export const tmp = (prefix = "sf-") => {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  scratch.push(dir);
  return dir;
};

export const REVIEWERS = NAMES.map((n) => `software-factory:sdlc-review-${n}`);

export const finished = '\nSOFTWARE_FACTORY_RESULT: {"status":"finished"}';

// `by_type` maps an agent type to how many were spawned; completions and failures
// are only counted in the totals beside it.
export const byType = (types = REVIEWERS, count = 1) => Object.fromEntries(types.map((t) => [t, count]));

// The JSON `claude -p --output-format json` prints when a run ends.
export const output = (over = {}) => ({
  session_id: "sess-1",
  is_error: false,
  terminal_reason: "completed",
  num_turns: 12,
  duration_ms: 60_000,
  total_cost_usd: 0.2,
  permission_denials: [],
  modelUsage: { "claude-sonnet-5-5": { costUSD: 0.2 } },
  subagent_stats: { spawned: 0, completed: 0, failed: 0, by_type: {} },
  result: `Done.${finished}`,
  ...over,
});

// The review file a finished pr-review run leaves in its checkout.
export const reviewBody = (outcome = "Approved") =>
  `## PR Review — x\n\n**Overall:** ${outcome}\n\nFine.\n\n---\n*Generated by \`/pr-review\` · Lenses: requirements*`;

export const reviewOutput = (over = {}) =>
  output({
    subagent_stats: { spawned: 6, completed: 6, failed: 0, by_type: byType() },
    ...over,
  });

// A set of dependencies that records every call in order.
export const makeDeps = (over = {}) => {
  const calls = [];
  const record =
    (name, value) =>
    async (...args) => {
      calls.push([name, ...args]);
      return typeof value === "function" ? value(...args) : value;
    };
  const deps = {
    calls,
    config: {
      model: "sonnet",
      base: "main",
      repo: "/work/repo",
      maxTurns: 80,
      runTimeoutMs: 1_800_000,
      trustedAuthors: ["VTHoop"],
    },
    linear: { setStatus: record("linear.setStatus") },
    git: {
      addWorktree: record("git.addWorktree", () => "/work/wt/hea-1"),
      addReviewCheckout: record("git.addReviewCheckout", () => "/work/review/pr-7"),
      removeWorktree: record("git.removeWorktree"),
    },
    github: {
      findPr: record("github.findPr", () => ({ number: 7 })),
      comment: record("github.comment"),
    },
    files: {
      remove: record("files.remove"),
      read: record("files.read", () => reviewBody()),
    },
    claude: record("claude", () => output()),
    ...over,
  };
  return deps;
};
