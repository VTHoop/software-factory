import assert from "node:assert/strict";
import { describe, it } from "node:test";
import { createGithub, previewUrl } from "../../orchestrator/github.mjs";

const config = {
  githubRepo: "VTHoop/disciplined-sidekick",
  trustedAuthors: ["VTHoop"],
  previewAuthors: ["vercel"],
};

// A fake `gh`: replies by the first matching key found in the joined arguments.
const fakeRun = (replies) => {
  const calls = [];
  const run = async (file, args, opts = {}) => {
    calls.push({ file, args, opts });
    const line = args.join(" ");
    const key = Object.keys(replies).find((k) => line.includes(k));
    if (!key) throw new Error(`unexpected gh call: ${line}`);
    const reply = replies[key];
    return { stdout: typeof reply === "string" ? reply : JSON.stringify(reply) };
  };
  return { run, calls };
};
const gh = (replies) => {
  const { run, calls } = fakeRun(replies);
  return { github: createGithub(config, run), calls };
};
// A comment as the REST API returns it, in the pages `gh api --paginate --slurp` prints.
const comment = (login, body) => ({ user: { login }, author_association: "NONE", body });
const pages = (...comments) => [comments];
// A comment as `gh pr view --json comments` returns it, which the preview lookup still reads.
const jsonComment = (login, body) => ({ author: { login }, body });
const review = (outcome) => `## PR Review\n\n**Overall:** ${outcome}\n\n---\n*Generated by \`/pr-review\`*`;

describe("github", () => {
  it("targets the configured repo on every call", async () => {
    const { github, calls } = gh({ "pr list": [], "pr view": { headRefOid: "abc" }, "issues/7/comments": pages() });
    await github.findPr("b");
    await github.headSha(7);
    await github.response(7);
    const [api, ...rest] = [calls.at(-1), ...calls.slice(0, -1)];
    assert.ok(rest.every((c) => c.args.slice(0, 2).join(" ") === "-R VTHoop/disciplined-sidekick"));
    assert.ok(api.args.some((a) => a.startsWith("repos/VTHoop/disciplined-sidekick/issues/7/comments")));
  });

  it("reads comments from the REST API, every page, where the App's login is name[bot]", async () => {
    const { github, calls } = gh({ "issues/7/comments": pages() });
    await github.response(7);
    assert.deepEqual(calls[0].args.slice(0, 3), ["api", "--paginate", "--slurp"]);
  });

  it("has a time limit on every call", async () => {
    const { github, calls } = gh({ "pr list": [] });
    await github.findPr("b");
    assert.ok(calls.every((c) => c.opts.timeoutMs > 0));
  });

  describe("findPr", () => {
    const pr = (over) => ({
      number: 7,
      url: "u",
      headRefName: "pathooper83/hea-1-x",
      isCrossRepository: false,
      headRepository: { nameWithOwner: "VTHoop/disciplined-sidekick" },
      ...over,
    });

    it("returns the PR from a branch in the repo", async () => {
      const { github } = gh({ "pr list": [pr({})] });
      assert.equal((await github.findPr("b")).number, 7);
    });

    it("ignores a fork PR", async () => {
      const fork = pr({ isCrossRepository: true, headRepository: { nameWithOwner: "evil/x" } });
      const { github } = gh({ "pr list": [fork] });
      assert.equal(await github.findPr("b"), null);
    });

    it("is null when there is no PR", async () => {
      assert.equal(await gh({ "pr list": [] }).github.findPr("b"), null);
    });
  });

  it("returns the latest trusted response comment", async () => {
    const comments = [
      comment("VTHoop", "## Response to /pr-review\nfirst"),
      comment("stranger", "## Response to /pr-review\nfake"),
      comment("VTHoop", "## Response to /pr-review\nsecond"),
    ];
    assert.match(await gh({ "issues/7/comments": [comments.slice(0, 2), comments.slice(2)] }).github.response(7), /second/);
  });

  describe("github reads and writes", () => {
  it("posts a PR comment from stdin", async () => {
    const { github, calls } = gh({ "pr comment": "" });
    await github.comment(7, "hello");
    assert.deepEqual(calls[0].args.slice(2, 6), ["pr", "comment", "7", "--body-file"]);
    assert.equal(calls[0].opts.input, "hello");
  });

  it("reads the head commit of a PR", async () => {
    const { github } = gh({ "pr view": { headRefOid: "abc123" } });
    assert.equal(await github.headSha(7), "abc123");
  });

  it("reads the state of a PR", async () => {
    const { github } = gh({ "pr view": { state: "MERGED" } });
    assert.equal(await github.prState(7), "MERGED");
  });
});

describe("ciState", () => {
    const runs = (...r) => ({ check_runs: r });
    const state = (r) => gh({ "check-runs": [r] }).github.ciState("abc");

    it("names the repo in the endpoint, because `gh api` has no -R flag", async () => {
      const { github, calls } = gh({ "check-runs": [runs()] });
      await github.ciState("abc");
      assert.equal(calls[0].args[0], "api");
      assert.ok(calls[0].args.includes("repos/VTHoop/disciplined-sidekick/commits/abc/check-runs?per_page=100"));
    });

    it("reads every page of check runs", async () => {
      const { github, calls } = gh({ "check-runs": [runs({ status: "completed", conclusion: "success" }), runs({ status: "in_progress" })] });
      assert.equal(await github.ciState("abc"), "pending");
      assert.ok(calls[0].args.includes("--paginate") && calls[0].args.includes("--slurp"));
    });

    it("is none when the commit has no checks", async () => assert.equal(await state(runs()), "none"));
    it("is pending while any check is running", async () => {
      assert.equal(await state(runs({ status: "completed", conclusion: "success" }, { status: "in_progress" })), "pending");
    });
    it("is failure when any completed check failed", async () => {
      assert.equal(await state(runs({ status: "completed", conclusion: "success" }, { status: "completed", conclusion: "failure" })), "failure");
    });
    it("is success when all checks passed or were skipped", async () => {
      assert.equal(await state(runs({ status: "completed", conclusion: "success" }, { status: "completed", conclusion: "skipped" })), "success");
    });
  });
});

describe("previewUrl", () => {
  it("takes a Vercel link from a listed preview author", () => {
    const comments = [jsonComment("vercel", "Preview: https://app-git-x-team.vercel.app/ ok")];
    assert.equal(previewUrl(comments, ["vercel"]), "https://app-git-x-team.vercel.app/");
  });

  it("ignores a stranger who registered a lookalike login", () => {
    const comments = [jsonComment("vercel-preview", "https://phish.vercel.app/")];
    assert.equal(previewUrl(comments, ["vercel"]), undefined);
  });

  it("ignores a link that only mentions vercel.app in its query", () => {
    const comments = [jsonComment("vercel", "https://evil.example/?next=a.vercel.app")];
    assert.equal(previewUrl(comments, ["vercel"]), undefined);
  });
});

describe("prDetails", () => {
  it("finds the preview only from a listed preview author", async () => {
    const data = {
      number: 7,
      url: "u",
      body: "b",
      comments: [jsonComment("vercel-preview", "https://phish.vercel.app/"), jsonComment("vercel", "https://real.vercel.app/")],
    };
    const details = await gh({ "pr view": data }).github.prDetails(7);
    assert.equal(details.previewUrl, "https://real.vercel.app/");
  });
});

describe("github with a GitHub App", () => {
  const appConfig = { ...config, appLogin: "factory[bot]", env: { GH_TOKEN: "ghs_x" } };
  const app = (replies) => {
    const { run, calls } = fakeRun(replies);
    return { github: createGithub(appConfig, run), calls };
  };

  it("runs every gh call with the App's environment", async () => {
    const { github, calls } = app({ "pr list": [], "issues/7/comments": pages() });
    await github.findPr("b");
    await github.response(7);
    assert.ok(calls.every((c) => c.opts.env?.GH_TOKEN === "ghs_x"));
  });

  it("reads the App's response comment, and ignores a stranger's", async () => {
    const { github } = app({
      "issues/7/comments": pages(comment("factory[bot]", "## Response to /pr-review\nreal"), comment("stranger", "## Response to /pr-review\nfake")),
    });
    assert.match(await github.response(7), /real/);
  });

  it("starts nothing for a fork PR", async () => {
    const fork = { number: 7, url: "u", headRefName: "x/y", isCrossRepository: true, headRepository: { nameWithOwner: "evil/disciplined-sidekick" } };
    const { github } = app({ "pr list": [fork] });
    assert.equal(await github.findPr("x/y"), null);
  });
});

describe("github env as a function", () => {
  it("asks for the environment on every gh call", async () => {
    let n = 0;
    const { run, calls } = fakeRun({ "pr list": [], "pr view": { headRefOid: "abc" } });
    const github = createGithub({ ...config, env: () => ({ GH_TOKEN: `t${++n}` }) }, run);
    await github.findPr("b");
    await github.headSha(7);
    assert.deepEqual(calls.map((c) => c.opts.env.GH_TOKEN), ["t1", "t2"]);
  });
});
